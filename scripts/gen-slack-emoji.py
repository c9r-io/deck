def main(src: str, sha: str) -> None:
    raw = Path(src).read_bytes()
    data = json.loads(raw)
    pairs = {}
    for e in data:
        for name in e.get("short_names") or [e["short_name"]]:
            pairs.setdefault(name, e["unified"].lower())
    if not all(c in "0123456789abcdef" for c in sha) or len(sha) != 40:
        raise SystemExit("commit sha must be 40 hex characters")
    body = ",".join(f"{n}:{u}" for n, u in sorted(pairs.items()))
    if "'" in body or "\\" in body:
        raise SystemExit("unexpected character in the table")
    out = Path(__file__).resolve().parent.parent / "app/ui/js/slack-emoji.js"
    notice = "\n".join("// " + line if line else "//" for line in LICENSE.splitlines())
    out.write_text(f"""// slack-emoji.js — Slack's standard emoji short names → the characters they show
// Part of deck's no-build frontend: native ES modules, no bundler.
//
// # Contract
// GENERATED by scripts/gen-slack-emoji.py from iamcal/emoji-data
// commit {sha} (emoji.json SHA-256 {hashlib.sha256(raw).hexdigest()}); do not edit.
// `slackEmoji(name)` is the character of a standard short name (a skin tone
// suffix `::skin-tone-N` is dropped), or null: a workspace's custom emoji has
// no character, and the caller shows `:name:` instead.
//
// emoji-data notice:
{notice}

const TABLE = '{body}';
let map = null;

export function slackEmoji(name) {{
  if (!map) {{
    map = new Map();
    for (const pair of TABLE.split(',')) {{
      const at = pair.lastIndexOf(':');
      map.set(pair.slice(0, at), pair.slice(at + 1));
    }}
  }}
  const unified = map.get(String(name || '').split('::')[0]);
  return unified ? String.fromCodePoint(...unified.split('-').map(hex => parseInt(hex, 16))) : null;
}}
""")
    print(f"wrote {out} ({len(pairs)} names)")


if __name__ == "__main__":
    main(*sys.argv[1:3])
