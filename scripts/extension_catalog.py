#!/usr/bin/env python3
"""Compose reviewed, bundled first-party extensions; never discover user plugins.

Only app/extensions/*.json is an input. Entries name Rust declarations and
native ES modules, not executable commands. The deterministic generated source
is checked in so source censuses, Node tests and code review see exactly what
Cargo embeds. Cargo refreshes it before compilation; CI --check rejects drift.
No runtime setting, network request, home directory or environment adds an entry.
"""

import argparse
import json
import pathlib
import re
import subprocess
import sys


ROOT = pathlib.Path(__file__).resolve().parents[1]
RUST = pathlib.Path("app/src-tauri/src/extensions/generated.rs")
JS = pathlib.Path("app/ui/js/extensions-generated.js")
KINDS = ("agent", "service", "translation")
FIELDS = {"id", "kind", "rust", "ui", "order", "selected"}


class CatalogError(ValueError):
    pass


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise CatalogError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def load(root):
    directory = root / "app/extensions"
    if directory.is_symlink() or not directory.is_dir():
        raise CatalogError("expected a real app/extensions directory")
    entries = []
    seen = {key: set() for key in ("id", "rust", "ui", "order")}
    for path in sorted(directory.glob("*.json")):
        if path.is_symlink() or not path.is_file():
            raise CatalogError(f"manifest is not a regular file: {path.name}")
        try:
            entry = json.loads(path.read_text(), object_pairs_hook=unique_object)
        except (ValueError, OSError) as error:
            raise CatalogError(f"{path.name}: {error}") from error
        if not isinstance(entry, dict) or set(entry) != FIELDS:
            raise CatalogError(f"{path.name}: expected exactly {sorted(FIELDS)}")
        identity = entry["id"]
        if not isinstance(identity, str) or not re.fullmatch(r"[a-z][a-z0-9-]{0,63}", identity):
            raise CatalogError(f"{path.name}: invalid id")
        if path.stem != identity:
            raise CatalogError(f"{path.name}: filename must match id")
        if entry["kind"] not in KINDS:
            raise CatalogError(f"{identity}: unknown extension kind")
        if type(entry["order"]) is not int or not 0 <= entry["order"] <= 10000:
            raise CatalogError(f"{identity}: order must be a bounded integer")
        if type(entry["selected"]) is not bool or (entry["selected"] and entry["kind"] != "translation"):
            raise CatalogError(f"{identity}: only a translation provider may be selected")
        rust = entry["rust"]
        if not isinstance(rust, str) or not re.fullmatch(r"crate(?:::[A-Za-z_][A-Za-z_0-9]*)+", rust):
            raise CatalogError(f"{identity}: invalid Rust declaration path")
        ui = entry["ui"]
        if not isinstance(ui, str) or not re.fullmatch(r"extension-[a-z][a-z0-9-]*\.js", ui):
            raise CatalogError(f"{identity}: UI must name a bundled extension ES module")
        source = root / "app/ui/js" / ui
        if source.is_symlink() or not source.is_file():
            raise CatalogError(f"{identity}: missing regular UI module {ui}")
        if not re.search(r"export\s+const\s+CONTRIBUTION\b", source.read_text()):
            raise CatalogError(f"{identity}: UI module must export CONTRIBUTION")
        for key in seen:
            if entry[key] in seen[key]:
                raise CatalogError(f"{identity}: duplicate {key}")
            seen[key].add(entry[key])
        entries.append(entry)
    if sum(entry["selected"] for entry in entries) != 1:
        raise CatalogError("exactly one translation engine must be selected")
    # A forgotten manifest must not quietly leave a first-party UI module out.
    modules = {path.name for path in (root / "app/ui/js").glob("extension-*.js")}
    if modules != seen["ui"]:
        raise CatalogError("unregistered extension UI modules: " + ", ".join(sorted(modules - seen["ui"])))
    return sorted(entries, key=lambda entry: entry["order"])


def render(entries):
    rust = [
        "//! Generated by scripts/extension_catalog.py from app/extensions/*.json.",
        "//! Reviewed source only; no runtime discovery or activation. Do not edit.",
        "",
    ]
    tables = (
        ("service", "SERVICES", "super::ServiceIntegration"),
        ("agent", "AGENT_ADAPTERS", "crate::agent_status::AgentAdapter"),
        ("translation", "TRANSLATION_PROVIDERS", "crate::intelligence::provider::TranslationProviderEntry"),
    )
    for kind, name, value_type in tables:
        rust.append(f"pub(super) const {name}: &[{value_type}] = &[")
        rust.extend(f"    {entry['rust']}," for entry in entries if entry["kind"] == kind)
        rust.extend(["];", ""])
    selected = next(entry["id"] for entry in entries if entry["selected"])
    rust.extend([f'pub(super) const TRANSLATION_ENGINE: &str = "{selected}";', ""])
    code = "\n".join(rust)
    # These tests compare independent declarations: manifest identities and
    # the typed descriptors' actual identities must agree at every position.
    code += "\n#[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    fn manifest_identities_match_typed_descriptors() {\n"
    for kind, name, _ in tables:
        field = "source" if kind == "agent" else "id"
        expected = ", ".join(json.dumps(entry["id"]) for entry in entries if entry["kind"] == kind)
        code += f"        assert_eq!(\n            {name}.iter().map(|entry| entry.{field}).collect::<Vec<_>>(),\n            [{expected}]\n        );\n"
    code += "    }\n}\n"
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=code, text=True, capture_output=True, cwd=ROOT,
    )
    if formatted.returncode:
        raise CatalogError("rustfmt could not format the generated catalog: " + formatted.stderr)
    code = formatted.stdout
    js = [
        "// Generated by scripts/extension_catalog.py from app/extensions/*.json.",
        "// Bundled native ES modules only. Importing never activates a capability.",
    ]
    for index, entry in enumerate(entries):
        js.append(f"import {{ CONTRIBUTION as entry{index} }} from './{entry['ui']}';")
    js.append("")
    js.append("export const EXTENSION_CONTRIBUTIONS = Object.freeze([")
    js.extend(f"  entry{index}," for index, _ in enumerate(entries))
    js.extend([
        "]);", "",
        "// Identity parity is checked before Settings mounts anything.",
        "export const EXTENSION_IDENTITIES = Object.freeze([",
    ])
    js.extend("  Object.freeze(" + json.dumps({"id": entry["id"], "kind": entry["kind"]}, separators=(", ", ": ")) + ")," for entry in entries)
    js.extend([
        "]);", "",
        "if (EXTENSION_CONTRIBUTIONS.some((entry, index) => entry.id !== EXTENSION_IDENTITIES[index].id)) {",
        "  throw new Error('Extension manifest and UI identity disagree');",
        "}", "",
    ])
    return {RUST: code, JS: "\n".join(js)}


def compose(root, check=False):
    outputs = render(load(root))
    changed = []
    for relative in outputs:
        path = root / relative
        if path.is_symlink() or any(parent.is_symlink() for parent in path.parents if parent != root and parent.is_relative_to(root)):
            raise CatalogError(f"generated output must not be a symlink: {relative}")
    for relative, content in outputs.items():
        path = root / relative
        if path.exists() and path.read_text() == content:
            continue
        changed.append(str(relative))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if check and changed:
        raise CatalogError("stale generated catalog (run python3 scripts/extension_catalog.py): " + ", ".join(changed))
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="refuse stale generated source without writing")
    args = parser.parse_args()
    try:
        changed = compose(ROOT, check=args.check)
    except (CatalogError, OSError) as error:
        print(f"extension catalog: {error}", file=sys.stderr)
        return 1
    print("extension catalog: " + ("updated " + ", ".join(changed) if changed else "current"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
